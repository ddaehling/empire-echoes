const letter = /[\p{L}\p{N}\p{M}_]/u;
const literal = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const formPattern = (form) => form.split(/[\s\p{Pd}]+/u)
  .map((part) => literal(part).replace(/[’']/g, "[’']"))
  .join("[\\s\\p{Pd}]+");
const matchers = entries.flatMap((record, priority) => record.forms.map((form) => ({
  record, priority, pattern: new RegExp(formPattern(form), "giu"),
})));
const hasBoundary = (context, start, end) =>
  !letter.test(context.slice(0, start).match(/.$/u)?.[0] || "") &&
  !letter.test(context.slice(end).match(/^./u)?.[0] || "");
const normaliseWord = (text) => text.toLocaleLowerCase("en").replace(/[’']/g, "'");

function selectedRange(word, context, start, end) {
  if (Number.isInteger(start) && Number.isInteger(end)) {
    if (start < 0 || end <= start || end > context.length ||
      normaliseWord(context.slice(start, end)) !== normaliseWord(word) ||
      !hasBoundary(context, start, end)) return null;
    return { start, end };
  }
  // Without offsets, resolve only an unambiguous occurrence. Never silently
  // attach the help to the first of several identical words.
  if (start != null || end != null) return null;
  const pattern = new RegExp(formPattern(word), "giu");
  const matches = [...context.matchAll(pattern)].filter((match) =>
    hasBoundary(context, match.index, match.index + match[0].length));
  return matches.length === 1
    ? { start: matches[0].index, end: matches[0].index + matches[0][0].length }
    : null;
}

function localSentence(context, start, end) {
  const left = context.slice(0, start).search(/[^.!?\n]*$/u);
  const right = context.slice(end).search(/[.!?\n]/u);
  return context.slice(left, right < 0 ? context.length : end + right);
}

/** Match the longest authored expression containing the selected UTF-16 range. */
export function lookupGlossary({ word, context, start, end } = {}) {
  if (typeof word !== "string" || !word.trim() || word.length > 120 ||
    typeof context !== "string" || !context || context.length > 20000) return null;
  const selected = selectedRange(word, context, start, end);
  if (!selected) return null;
  const candidates = [];
  for (const { record, priority, pattern } of matchers) {
    pattern.lastIndex = 0;
    for (const match of context.matchAll(pattern)) {
      const from = match.index, to = from + match[0].length;
      if (from > selected.start || to < selected.end || !hasBoundary(context, from, to)) continue;
      if (record.unless?.test(localSentence(context, from, to))) continue;
      candidates.push({ record, priority, term: match[0] });
    }
  }
  candidates.sort((a, b) => b.term.length - a.term.length || a.priority - b.priority);
  const found = candidates[0];
  if (!found) return null;
  return {
    term: found.term,
    meaning: found.record.meaning,
    inContext: found.record.inContext,
    examples: [...found.record.examples],
    context,
    source: "glossary",
  };
}
